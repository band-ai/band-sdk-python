"""Maintain the historical contract-tool wheel closure; SDK runtime dependencies use the root uv.lock."""

from __future__ import annotations

import email
import hashlib
import json
import sys
import urllib.request
import zipfile
from email.message import Message
from pathlib import Path
from typing import Any, NoReturn

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from contracts.spec.tools.paths import CONTRACTS_ROOT as ROOT

# The lock target: Linux x86_64 / CPython 3.12, no extras.
TARGET = {
    **default_environment(),
    "os_name": "posix",
    "sys_platform": "linux",
    "platform_system": "Linux",
    "platform_machine": "x86_64",
    "implementation_name": "cpython",
    "platform_python_implementation": "CPython",
    "python_version": "3.12",
    "python_full_version": "3.12.3",
    "implementation_version": "3.12.3",
    "extra": "",
}


def drift(message: str) -> NoReturn:
    raise SystemExit(
        f"lockpython.py: .cache/requirements drifted from requirements-dev.in: {message}"
    )


def closure(
    roots: list[Requirement], wheels: dict[str, tuple[Path, Message]]
) -> list[tuple[Path, Message]]:
    """The cached wheels reachable from the pinned roots (impl L11): every root is an exact pin, every
    requirement on the target resolves to exactly one cached wheel inside its range, and nothing is stray."""
    found, queue = {}, []
    for root in roots:
        pins = [spec for spec in root.specifier if spec.operator == "=="]
        if len(pins) != 1 or len(root.specifier) != 1:
            drift(f"{root} is unpinned: every root must be an exact == pin")
        queue.append((root, "requirements-dev.in"))
    while queue:
        requirement, parent = queue.pop()
        if requirement.marker and not requirement.marker.evaluate(TARGET):
            continue
        name = canonicalize_name(requirement.name)
        if name not in wheels:
            drift(f"{requirement} (from {parent}) has no cached wheel")
        wheel, meta = wheels[name]
        if not requirement.specifier.contains(meta["Version"], prereleases=True):
            drift(f"{requirement} (from {parent}) excludes the cached {wheel.name}")
        if name in found:
            continue
        found[name] = (wheel, meta)
        queue += [
            (Requirement(item), meta["Name"])
            for item in meta.get_all("Requires-Dist", [])
        ]
    stray = sorted(
        wheel.name for name, (wheel, _) in wheels.items() if name not in found
    )
    if stray:
        drift("stray " + ", ".join(stray))
    return [found[name] for name in sorted(found)]


def main() -> None:
    roots = [
        Requirement(line.split("#", 1)[0].strip())
        for line in (ROOT / "requirements-dev.in").read_text().splitlines()
        if line.split("#", 1)[0].strip()
    ]
    wheels = {}
    for wheel in sorted((ROOT / ".cache/requirements").glob("*.whl")):
        with zipfile.ZipFile(wheel) as archive:
            path = next(
                name
                for name in archive.namelist()
                if name.endswith(".dist-info/METADATA")
            )
            meta = email.message_from_bytes(archive.read(path))
        name = canonicalize_name(meta["Name"])
        if name in wheels:
            drift(f"two cached wheels for {name}: {wheels[name][0].name}, {wheel.name}")
        wheels[name] = (wheel, meta)
    rows: list[dict[str, Any]] = []
    for wheel, meta in closure(roots, wheels):
        name, version = meta["Name"], meta["Version"]
        checksum = hashlib.sha256(wheel.read_bytes()).hexdigest()
        source = f"https://pypi.org/pypi/{name}/{version}/json"
        with urllib.request.urlopen(source, timeout=20) as response:
            published = json.load(response)
        artifact = next(
            (item for item in published["urls"] if item["filename"] == wheel.name), None
        )
        if (
            artifact is None
            or artifact["yanked"]
            or artifact["digests"]["sha256"] != checksum
        ):
            raise SystemExit(
                f"lockpython.py: {wheel.name} is not a published, unyanked PyPI artifact with this digest"
            )
        rows.append(
            {
                "name": name,
                "version": version,
                "wheel": wheel.name,
                "sha256": checksum,
                "metadata_source": source,
                "artifact_url": artifact["url"],
                "requires_python": meta["Requires-Python"],
                "requires_dist": meta.get_all("Requires-Dist", []),
            }
        )
    lines = [
        "# Linux x86_64 / CPython 3.12 build and specification tooling.",
        "# Generated by spec/tools/lockpython.py after PyPI hash verification.",
    ]
    lines += [
        f"{row['name']}=={row['version']} --hash=sha256:{row['sha256']}" for row in rows
    ]
    (ROOT / "requirements-dev.lock").write_text("\n".join(lines) + "\n")
    build_names = {"setuptools", "build", "packaging", "pyproject_hooks", "wheel"}
    build_rows = [
        row for row in rows if row["name"].replace("-", "_").lower() in build_names
    ]
    (ROOT / "requirements-build.lock").write_text(
        "\n".join(
            lines[:2]
            + [
                f"{row['name']}=={row['version']} --hash=sha256:{row['sha256']}"
                for row in build_rows
            ]
        )
        + "\n"
    )
    (ROOT / "spec/conformance/dependency-manifest.json").write_text(
        json.dumps(
            {
                "profile": "band-contract/python-tools/1",
                "target": {"platform": "linux_x86_64", "python": "3.12"},
                "runtime_dependencies": [],
                "packages": rows,
            },
            indent=2,
        )
        + "\n"
    )
    sys.stdout.write(
        str(f"{len(rows)} verified wheel hashes; {len(build_rows)} build-only packages")
        + "\n"
    )


if __name__ == "__main__":
    main()
