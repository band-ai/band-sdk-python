def rows(catalog: dict[str, Any] | None = None) -> dict[str, int]:
    catalog = catalog or json.loads(CATALOG.read_text())
    return {row["id"]: len(row["acceptance"]) for row in catalog["requirements"]}


def verify(
    tool: str, names: list[str], catalog: dict[str, Any] | None = None
) -> dict[str, list[str]]:
    """The tool ran exactly its tagged checks, once each; every tag names a catalog row and item."""
    names = list(names)
    duplicates = sorted({name for name in names if names.count(name) > 1})
    assert not duplicates, ("check names run twice", duplicates)
    tagged = TAGS[tool]
    assert set(names) == set(tagged), (
        "untagged checks",
        sorted(set(names) - set(tagged)),
        "tags for checks that did not run",
        sorted(set(tagged) - set(names)),
    )
    known = rows(catalog)
    for name, tags in tagged.items():
        check_tags(name, tags, known)
    return {name: list(tagged[name]) for name in names}


def check_tags(name: str, tags: tuple[str, ...], known: dict[str, int]) -> None:
    """Requirement rows and items that exist, or exactly one explicit marker; never a bare ()."""
    assert tags, (
        name,
        "bare () tag: name requirement rows, TOOLING or NO_ROW + a spec file",
    )
    if any(tag == TOOLING or tag.startswith(NO_ROW) for tag in tags):
        assert len(tags) == 1, (name, tags, "a marker stands alone")
        assert tags[0] == TOOLING or (SPEC / tags[0][len(NO_ROW) :]).is_file(), (
            name,
            tags,
        )
        return
    for tag in tags:
        identifier, _, item = tag.partition("/")
        assert identifier in known, (name, tag)
        assert not item or 1 <= int(item) <= known[identifier], (name, tag)
